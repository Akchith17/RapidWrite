import 'package:flutter_test/flutter_test.dart';
import 'package:stylus_handwriting_evaluator/models/evaluation_result.dart';
import 'package:stylus_handwriting_evaluator/models/handwriting_stroke.dart';
import 'package:stylus_handwriting_evaluator/models/stroke_point.dart';
import 'package:stylus_handwriting_evaluator/models/practice_settings.dart';
import 'package:stylus_handwriting_evaluator/services/speed_calculator_service.dart';
import 'package:stylus_handwriting_evaluator/services/aesthetic_evaluator_service.dart';
import 'package:stylus_handwriting_evaluator/services/digital_ink_service.dart';

void main() {
  group('RapidWrite Complete Submission & Analysis Workflow', () {
    test('Workflow cleanly decouples speed, OCR accuracy, and 5-stage aesthetic scoring', () {
      const targetSentence = 'The quick brown fox jumps over the lazy dog';
      const recognizedOcr = 'The quick brown fox jumps over the lazy dog';

      // 1. Simulate handwriting strokes for 9 words over 15 seconds
      final strokes = <HandwritingStroke>[];
      int currentTime = 1000;
      double currentX = 50.0;

      for (int w = 0; w < 9; w++) {
        for (int l = 0; l < 4; l++) {
          strokes.add(HandwritingStroke(
            points: [
              StrokePoint(x: currentX, y: 120, timestampMs: currentTime, pressure: 0.7),
              StrokePoint(x: currentX + 6, y: 145, timestampMs: currentTime + 100, pressure: 0.8),
              StrokePoint(x: currentX + 12, y: 120, timestampMs: currentTime + 200, pressure: 0.7),
            ],
          ));
          currentX += 16.0;
          currentTime += 250;
        }
        currentX += 24.0; // Word space
        currentTime += 400; // Pause between words
      }

      // 2. Compute Independent Speed Metrics (WPM / CPM / Duration)
      final metrics = SpeedCalculatorService.calculate(
        startTimeMs: 1000,
        endTimeMs: currentTime,
        strokes: strokes,
      );

      expect(metrics.strokeCount, equals(36));
      expect(metrics.activeDrawingTimeMs, greaterThan(0));
      expect(metrics.activeVelocityPxPerSec, greaterThan(0));

      // 3. Compute Independent OCR Accuracy
      final charAccuracy = DigitalInkService.calculateCharacterAccuracy(targetSentence, recognizedOcr);
      final wordAccuracy = DigitalInkService.calculateWordAccuracy(targetSentence, recognizedOcr);

      expect(charAccuracy, equals(100.0));
      expect(wordAccuracy, equals(100.0));

      // 4. Compute Official 5-Stage Aesthetic Evaluation
      final aesthetic = AestheticEvaluatorService.evaluate(
        strokes,
        targetSentence: targetSentence,
        ageCohort: 'Senior / College Cohort',
      );

      // Verify aesthetic evaluation was generated by the 5-stage algorithm
      expect(aesthetic.evaluatedBy, equals('RapidWrite 5-Stage Aesthetic Engine'));
      expect(aesthetic.overallAestheticScore, inInclusiveRange(30.0, 99.0));
      expect(aesthetic.readabilityScore, inInclusiveRange(35.0, 99.0));
      expect(aesthetic.letterFormationScore, inInclusiveRange(30.0, 98.0));
      expect(aesthetic.spacingScore, inInclusiveRange(30.0, 98.0));
      expect(aesthetic.alignmentScore, inInclusiveRange(30.0, 99.0));
      expect(aesthetic.consistencyScore, inInclusiveRange(30.0, 98.0));
      expect(aesthetic.visualOrganizationScore, inInclusiveRange(35.0, 98.0));
      expect(['A+', 'A', 'B+', 'B', 'C+', 'C'].contains(aesthetic.grade), isTrue);
      expect(aesthetic.critiqueTitle.isNotEmpty, isTrue);
      expect(aesthetic.coachingTips.isNotEmpty, isTrue);

      // 5. Build Unified EvaluationResult Container
      final result = EvaluationResult(
        targetSentence: targetSentence,
        recognizedText: recognizedOcr,
        characterAccuracy: charAccuracy,
        wordAccuracy: wordAccuracy,
        metrics: metrics,
        aesthetic: aesthetic,
        timestamp: DateTime.now(),
        targetWpm: 25,
        recommendedDurationSec: 21,
      );

      expect(result.grossWpm, greaterThan(0));
      expect(result.netWpm, greaterThan(0));
      expect(result.speedPenaltyWpm, equals(0.0)); // 100% accuracy = 0 penalty
      expect(result.aesthetic.evaluatedBy, equals('RapidWrite 5-Stage Aesthetic Engine'));
    });

    test('Calibrating personal baseline and evaluating subsequent practice demonstrates Stage 4 & 5', () {
      const sentence = 'Students attend classes every day to gain knowledge';

      final baselineStrokes = [
        HandwritingStroke(points: [
          StrokePoint(x: 20, y: 100, timestampMs: 1000),
          StrokePoint(x: 35, y: 135, timestampMs: 1100),
        ]),
        HandwritingStroke(points: [
          StrokePoint(x: 45, y: 102, timestampMs: 1200),
          StrokePoint(x: 60, y: 137, timestampMs: 1300),
        ]),
      ];

      // Stage 3: Calibrate baseline profile
      final profile = AestheticEvaluatorService.calibrateBaseline(
        strokes: baselineStrokes,
        targetSentence: sentence,
        userId: 'student_cohort_user',
      );

      expect(profile.userId, equals('student_cohort_user'));
      expect(profile.medianLetterHeight, closeTo(35.0, 2.0));
      expect(profile.personalStyleTags.isNotEmpty, isTrue);

      // Subsequent session evaluated with profile
      final practiceEval = AestheticEvaluatorService.evaluate(
        baselineStrokes,
        targetSentence: sentence,
        referenceProfile: profile,
      );

      expect(practiceEval.hasPersonalReference, isTrue);
      expect(practiceEval.personalStyleTags, equals(profile.personalStyleTags));
      expect(practiceEval.consistencyScore, greaterThan(30.0));
    });

    test('Age-cohort adaptiveness normalizes baseline for elementary school cohort', () {
      const schoolSentence = 'The quick brown fox jumps over the lazy dog';

      // Simulating younger student writing with natural larger letter heights and freehand drift
      final schoolStrokes = [
        HandwritingStroke(points: [
          StrokePoint(x: 10, y: 100, timestampMs: 1000),
          StrokePoint(x: 20, y: 155, timestampMs: 1100), // 55px tall (larger young script)
        ]),
        HandwritingStroke(points: [
          StrokePoint(x: 35, y: 108, timestampMs: 1200),
          StrokePoint(x: 45, y: 168, timestampMs: 1300), // 60px tall with unlined drift
        ]),
      ];

      final schoolEvaluation = AestheticEvaluatorService.evaluate(
        schoolStrokes,
        targetSentence: schoolSentence,
        ageCohort: 'School Students Cohort (Elementary / Middle School)',
      );

      expect(schoolEvaluation.overallAestheticScore, greaterThan(30.0));
      expect(schoolEvaluation.evaluatedBy, equals('RapidWrite 5-Stage Aesthetic Engine'));
    });
  });
}
